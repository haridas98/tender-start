const iskconExcludedTradePattern = /пив|алког|водоч|ликер|винн|вино|wine|winery|beer|brew|alcohol|meat|fish|seafood|chicken|poultry|мяс|рыб|икр|осетр|морепродукт|хмел|солод|птиц|индей|гусь|колбас|убойн|хладобойн/i
const technicalChemistryPattern = /хим|нефтехим|каучук|полимер|реагент|фарма|лаборатор|синтез/i

function plantVisibleText(plant: Plant) {
  return [
    plant.name,
    plant.legalName,
    plant.industry,
    ...(plant.products ?? []),
    ...(plant.purchaseCategories ?? []),
    ...(plant.equipment ?? []),
    ...(plant.logistics ?? []),
    ...(plant.needs ?? []).flatMap((need) => [need.materialName, need.note, need.spec]),
    ...(plant.procurementEvidence ?? []).flatMap((evidence) => [evidence.title, evidence.note, ...evidence.inferredNeeds]),
  ].join(' ')
}

export function visiblePlantEntries(entries: Array<[string, Plant]>) {
  return dedupeVisiblePlants(
    entries.filter(([, plant]) => {
      const visibleText = plantVisibleText(plant)
      if (iskconExcludedTradePattern.test(visibleText)) return false
      if (/спирт/i.test(visibleText) && !technicalChemistryPattern.test([plant.industry, ...plant.products].join(' '))) return false
      return true
    }),
  )
}

export const plants: Record<string, Plant> = Object.fromEntries(visiblePlantEntries(Object.entries(plantRecords))) as Record<string, Plant>

function dedupeVisiblePlants(entries: Array<[string, Plant]>) {
  const seen = new Set<string>()
  const result: Array<[string, Plant]> = []

  for (const [slug, plant] of entries) {
    const key = `${plant.region}:${plant.name}`.toLowerCase().replace(/["«»()]/g, '').replace(/\s+/g, ' ').trim()
    if (seen.has(key)) continue
    seen.add(key)
    result.push([slug, plant])
  }

  return result
}

