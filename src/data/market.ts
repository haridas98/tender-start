function eisSearch(query: string) {
  return `https://zakupki.gov.ru/epz/order/extendedsearch/results.html?searchString=${encodeURIComponent(query)}&morphology=on&recordsPerPage=_10&sortBy=UPDATE_DATE&sortDirection=false`
}

function procurementSearch(title: string, inferredNeeds: string[], query = title): PlantProcurementSignal {
  return {
    documents: ['извещение', 'ТЗ/спецификация', 'проект договора', 'протоколы', 'контракт'],
    inferredNeeds,
    note: 'Живой поиск по ЕИС/ЭТП. Найденные закупки нужно переносить в карточку отдельными подтвержденными строками с номером извещения и документами.',
    source: 'ЕИС закупки',
    sourceUrl: eisSearch(query),
    status: 'поиск в ЕИС/ЭТП',
    title,
  }
}

function profileSignal(title: string, inferredNeeds: string[], sourceUrl: string): PlantProcurementSignal {
  return {
    documents: ['карточка производителя', 'контакты', 'реквизиты'],
    inferredNeeds,
    note: 'Профильная гипотеза по производству. Это не тендерное подтверждение, а стартовая карта сырья и оборудования до проверки закупочных документов.',
    source: 'промышленный каталог / сайт производителя',
    sourceUrl,
    status: 'профильная гипотеза',
    title,
  }
}

